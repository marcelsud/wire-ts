import {
  create,
  createFileRegistry,
  toBinary,
  ScalarType,
  type DescEnum,
  type DescField,
  type DescMessage,
} from "@bufbuild/protobuf";
import {
  FileDescriptorSetSchema,
  type DescriptorProto,
  type FileDescriptorProto,
} from "@bufbuild/protobuf/wkt";
import {
  CodeGeneratorResponseSchema,
  type CodeGeneratorRequest,
  type CodeGeneratorResponse,
} from "@bufbuild/protobuf/wkt/google/protobuf/compiler/plugin_pb.js";
import { base64Encode } from "@bufbuild/protobuf/wire";

type Model = DescMessage | DescEnum;

/** Standard protoc/Buf plugin input. Repeated root= options select reachable types. */
export function generate(request: CodeGeneratorRequest): CodeGeneratorResponse {
  const roots: string[] = [];
  let runtime = "wire-typescript";
  for (const option of request.parameter.split(",").filter(Boolean)) {
    const equal = option.indexOf("=");
    const key = option.slice(0, equal);
    const value = option.slice(equal + 1);
    if (equal < 1 || !value) throw new Error(`Invalid plugin option: ${option}`);
    if (key === "root") roots.push(value);
    else if (key === "runtime") runtime = value;
    else throw new Error(`Unknown plugin option: ${key}`);
  }
  const registry = createFileRegistry(create(FileDescriptorSetSchema, { file: request.protoFile }));
  const selected = new Map<string, Model>();
  function visit(model: Model): void {
    if (selected.has(model.typeName)) return;
    if (model.file.proto.syntax !== "proto3") {
      throw new Error(`Only proto3 is supported: ${model.file.proto.name}`);
    }
    selected.set(model.typeName, model);
    if (model.kind === "message") {
      for (const field of model.fields) {
        if (field.message) visit(field.message);
        if (field.enum) visit(field.enum);
      }
    }
  }
  if (roots.length) {
    for (const root of roots) {
      const model = registry.get(root);
      if (!model || (model.kind !== "message" && model.kind !== "enum")) {
        throw new Error(`Unknown root message or enum: ${root}`);
      }
      visit(model);
    }
  } else {
    for (const model of registry) {
      if ((model.kind === "message" || model.kind === "enum") &&
          request.fileToGenerate.includes(model.file.proto.name)) visit(model);
    }
  }
  const models = [...selected.values()].sort((a, b) => a.typeName.localeCompare(b.typeName));
  const names = new Map<string, string>();
  const used = new Set(["createAdapter", "defineSchema", "WireMessage", "schema", "Uint8Array", "Record", "Readonly"]);
  for (const model of models) {
    const base = model.typeName.split(".").slice(model.file.proto.package ? model.file.proto.package.split(".").length : 0).join("_");
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(base)) {
      throw new Error(`Invalid protobuf identifier: ${model.typeName}`);
    }
    let name = base;
    let suffix = 2;
    while (used.has(name) || !validIdentifier(name)) name = `${base}_${suffix++}`;
    used.add(name);
    names.set(model.typeName, name);
  }
  const schema = prune(request.protoFile, new Set(selected.keys()));
  const encoded = base64Encode(toBinary(FileDescriptorSetSchema, create(FileDescriptorSetSchema, { file: schema })));
  const lines = [
    "// Generated by wire-typescript. Do not edit.",
    `import { createAdapter, defineSchema, type WireMessage } from ${JSON.stringify(runtime)};`,
    "",
    `const schema = defineSchema(${JSON.stringify(encoded)});`,
  ];
  function fieldType(field: DescField): string {
    const item = field.message ? names.get(field.message.typeName)! :
      field.enum ? names.get(field.enum.typeName)! : scalarType(field.scalar!);
    if (field.fieldKind === "list") return `readonly ${item}[]`;
    if (field.fieldKind === "map") return `Readonly<Record<string, ${item}>>`;
    return item;
  }
  for (const model of models) {
    const name = names.get(model.typeName)!;
    lines.push("", `/** ${model.typeName} */`);
    if (model.kind === "enum") {
      lines.push(`export const ${name} = {`);
      for (const value of model.values) {
        const key = value.name === "__proto__" ? `[${JSON.stringify(value.name)}]` : JSON.stringify(value.name);
        lines.push(`  ${key}: ${value.number},`);
      }
      lines.push("} as const;", "/** Proto3 enums remain open to values from newer schemas. */", `export type ${name} = number;`);
      continue;
    }
    lines.push(`export interface ${name} extends WireMessage {`);
    for (const member of model.members) {
      if (member.kind === "oneof") {
        lines.push(`  readonly ${JSON.stringify(member.name)}?:`);
        for (const field of member.fields) {
          lines.push(`    | { readonly case: ${JSON.stringify(field.name)}; readonly value: ${fieldType(field)} }`);
        }
        lines[lines.length - 1] += ";";
      } else {
        const optional = member.fieldKind !== "list" && member.fieldKind !== "map" && member.presence !== 2;
        lines.push(`  readonly ${JSON.stringify(member.name)}${optional ? "?" : ""}: ${fieldType(member)};`);
      }
    }
    lines.push("}", "", `export const ${name} = {`,
      `  ADAPTER: createAdapter<${name}>(schema, ${JSON.stringify(model.typeName)}),`, "} as const;");
  }
  return create(CodeGeneratorResponseSchema, {
    supportedFeatures: 1n,
    file: [{ name: "wire.ts", content: lines.join("\n") + "\n" }],
  });
}

function scalarType(type: ScalarType): string {
  switch (type) {
    case ScalarType.STRING: return "string";
    case ScalarType.BOOL: return "boolean";
    case ScalarType.BYTES: return "Uint8Array";
    case ScalarType.INT64: case ScalarType.UINT64: case ScalarType.SINT64:
    case ScalarType.FIXED64: case ScalarType.SFIXED64: return "bigint";
    default: return "number";
  }
}

const reserved = new Set(("await break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with yield let static implements interface package private protected public arguments eval abstract as asserts any bigint boolean constructor declare global infer intrinsic is keyof module namespace never number object out override readonly require satisfies string symbol type undefined unique unknown using").split(" "));

function validIdentifier(name: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) && !reserved.has(name);
}

/** Prune descriptors too, so unused models do not stay embedded in the runtime schema. */
function prune(files: FileDescriptorProto[], keep: Set<string>): FileDescriptorProto[] {
  function message(proto: DescriptorProto, prefix: string): DescriptorProto[] {
    const name = prefix ? `${prefix}.${proto.name}` : proto.name;
    const retained = keep.has(name);
    const children = proto.nestedType.flatMap((child) =>
      child.options?.mapEntry ? (retained ? [child] : []) : message(child, name));
    const enums = proto.enumType.filter((item) => keep.has(`${name}.${item.name}`));
    if (!retained && !children.length && !enums.length) return [];
    return [{ ...proto, nestedType: children, enumType: enums, extension: [],
      field: retained ? proto.field : [], oneofDecl: retained ? proto.oneofDecl : [] }];
  }
  return files.map((file) => {
    const { sourceCodeInfo: _, ...rest } = file;
    return { ...rest, service: [], extension: [],
      messageType: file.messageType.flatMap((item) => message(item, file.package)),
      enumType: file.enumType.filter((item) => keep.has(file.package ? `${file.package}.${item.name}` : item.name)) };
  });
}
